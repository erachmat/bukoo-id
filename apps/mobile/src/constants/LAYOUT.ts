/**
 * Layout constants for responsive design.
 *
 * Tablet breakpoint follows Material Design (600dp). Below this width a
 * screen is treated as a phone; at/above it, `useIsTablet()` returns true.
 *
 * `MAX_CONTENT_WIDTH` is the centered column width used on wide (tablet)
 * displays so content doesn't stretch edge-to-edge. Phones are unaffected
 * because every phone width is below this value.
 */
export const TABLET_BREAKPOINT = 600;

export const MAX_CONTENT_WIDTH = 720;
